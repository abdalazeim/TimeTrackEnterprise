"""Synchronisation models: devices, idempotent records and conflicts."""
from __future__ import annotations

import secrets
import uuid

from django.db import models


def new_device_token() -> str:
    return secrets.token_urlsafe(32)


class Device(models.Model):
    """A paired client (desktop installation, phone gateway, tablet...)."""

    PLATFORMS = (
        ("desktop", "Desktop"),
        ("android", "Android"),
        ("ios", "iOS"),
        ("web", "Web"),
        ("other", "Other"),
    )

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    name = models.CharField("الاسم", max_length=120)
    platform = models.CharField("المنصة", max_length=32, choices=PLATFORMS, default="desktop")
    app_version = models.CharField("الإصدار", max_length=32, blank=True, default="")
    token = models.CharField("الرمز", max_length=64, unique=True, default=new_device_token)
    is_active = models.BooleanField("نشط", default=True)
    created_by = models.CharField("أنشأه", max_length=64, blank=True, default="")
    created_at = models.DateTimeField(auto_now_add=True)
    last_seen_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        verbose_name = "جهاز"
        verbose_name_plural = "الأجهزة"
        ordering = ("-created_at",)
        indexes = [models.Index(fields=["is_active", "platform"])]

    def __str__(self) -> str:  # pragma: no cover - trivial
        return f"{self.name} ({self.platform})"


class SyncRecord(models.Model):
    """One idempotent change pushed by a device."""

    OPERATIONS = (
        ("create", "Create"),
        ("update", "Update"),
        ("delete", "Delete"),
    )
    STATUSES = (
        ("applied", "Applied"),
        ("conflict", "Conflict"),
        ("rejected", "Rejected"),
    )

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    client_id = models.UUIDField(
        "معرف العميل",
        null=True,
        blank=True,
        unique=True,
        help_text="UUID generated by the client; guarantees idempotent pushes.",
    )
    device = models.ForeignKey(Device, on_delete=models.CASCADE, related_name="records")
    entity = models.CharField("الكيان", max_length=64, db_index=True)
    entity_key = models.CharField("مفتاح الكيان", max_length=128, db_index=True)
    operation = models.CharField("العملية", max_length=16, choices=OPERATIONS, default="update")
    payload = models.JSONField("البيانات", default=dict, blank=True)
    base_revision = models.PositiveBigIntegerField("المراجعة الأساسية", default=0)
    server_revision = models.PositiveBigIntegerField("مراجعة الخادم", default=1)
    status = models.CharField("الحالة", max_length=16, choices=STATUSES, default="applied")
    error = models.TextField("الخطأ", blank=True, default="")
    created_at = models.DateTimeField(auto_now_add=True)
    applied_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        verbose_name = "سجل مزامنة"
        verbose_name_plural = "سجلات المزامنة"
        ordering = ("-created_at",)
        indexes = [
            models.Index(fields=["entity", "entity_key"]),
            models.Index(fields=["device", "created_at"]),
            models.Index(fields=["status"]),
        ]

    def __str__(self) -> str:  # pragma: no cover - trivial
        return f"{self.entity}:{self.entity_key} ({self.status})"


class SyncConflict(models.Model):
    """A push that could not be applied because the server had newer data."""

    RESOLUTIONS = (
        ("pending", "Pending"),
        ("local", "Keep client"),
        ("server", "Keep server"),
        ("merged", "Merged"),
    )

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    record = models.OneToOneField(
        SyncRecord, on_delete=models.CASCADE, related_name="conflict_detail"
    )
    server_payload = models.JSONField("بيانات الخادم", default=dict, blank=True)
    client_payload = models.JSONField("بيانات العميل", default=dict, blank=True)
    resolution = models.CharField(
        "طريقة الحل", max_length=16, choices=RESOLUTIONS, default="pending"
    )
    resolved_payload = models.JSONField("البيانات المعتمدة", default=dict, blank=True)
    resolved_by = models.CharField("حلّه", max_length=64, blank=True, default="")
    resolved_at = models.DateTimeField(null=True, blank=True)
    note = models.TextField("ملاحظة", blank=True, default="")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = "تعارض مزامنة"
        verbose_name_plural = "تعارضات المزامنة"
        ordering = ("-created_at",)

    def __str__(self) -> str:  # pragma: no cover - trivial
        return f"Conflict {self.pk} ({self.resolution})"
